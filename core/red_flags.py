def normalize_text(text: str) -> str:
    text = text.lower()
    text = re.sub(r'[^а-яё\s]', ' ', text)
    words = text.split()
    normalized_words = []
    for word in words:
        if len(word) <= 2: continue
        p = morph.parse(word)[0]
        normalized_words.append(p.normal_form)
    return ' '.join(normalized_words)

def check_red_flags(text: str, age: int) -> list[str]:
    clean = normalize_text(text)
    found = []
    for flag in RED_FLAGS:
        if flag in clean and flag not in found:
            found.append(flag)
    if age >= 60:
        for flag in AGE_RED_FLAGS:
            if flag in clean and flag not in found:
                found.append(f"{flag} (возрастной риск)")
    if "боль в груди" in clean or ("боль" in clean and "грудь" in clean):
        heart_markers = ["давить", "сжимать", "жжение", "гореть", "одышка", "страх", "паника", "покой", "постоянно"]
        muscle_markers = ["кашель", "мышца", "тянуть", "саднить", "движение"]
        has_heart = any(marker in clean for marker in heart_markers)
        has_muscle = any(marker in clean for marker in muscle_markers)
        if has_heart:
            if "боль в груди" in found: found.remove("боль в груди")
            found.append("боль в груди (сердечный риск)")
        elif has_muscle:
            if "боль в груди" in found: found.remove("боль в груди")
            found.append("MYALGIA_AFTER_COUGH")
    return found

def get_symptom_advice(text: str) -> dict:
    clean = normalize_text(text)
    found_categories = {}
    for category_name, data in SYMPTOM_CATEGORIES.items():
        if any(key in clean for key in data["keys"]):
            found_categories[category_name] = data
    return found_categories