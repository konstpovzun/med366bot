PANIC_ROOTS = ["умереть", "смерть", "умирать", "погибнуть", "скончаться", "помереть", "сдохнуть"]
CONTINUATION_WORDS = ["делать", "лечить", "опасно", "смертельно", "поможет", "что"]

def check_fact(claim: str, last_topic: str = None) -> dict | None:
    """Ищет факт в локальной базе."""
    clean_claim = re.sub(r'[^\w\s]', ' ', claim.lower()).strip()
    
    # 1. Проверка на панику
    if any(root in clean_claim for root in PANIC_ROOTS):
        return {
            "verdict": "🫂 <b>Пожалуйста, не паникуйте.</b>",
            "explanation": "Я — искусственный интеллект и не могу оценить реальную угрозу вашей жизни. Если вы чувствуете, что вам плохо, или боитесь за свое здоровье, пожалуйста, не оставайтесь один на один с этим страхом.\n\n"
                           "👉 <b>Пожалуйста, обратитесь к врачу или позвоните по номеру 103 (скорая помощь).</b>",
            "actions": "",
            "source": "Врач / Служба спасения 112",
            "url": "https://minzdrav.gov.ru"
        }

    # 2. Сначала ищем НОВЫЕ факты в тексте (приоритет выше, чем старая тема)
    for fact in FACTS_DB:
        if any(kw in clean_claim for kw in fact["keywords"]):
            return fact

    # 3. Если новых слов нет, но есть продолжение ("что делать") и last_topic
    if last_topic and any(word in clean_claim for word in CONTINUATION_WORDS):
        for fact in FACTS_DB:
            if fact.get("topic") == last_topic:
                return fact

    return None

def search_who(query: str) -> dict | None:
    try:
        search_url = f"https://www.who.int/ru/search?query={query}"
        headers = {'User-Agent': 'Mozilla/5.0'}
        response = requests.get(search_url, headers=headers, timeout=10)
        soup = BeautifulSoup(response.text, 'html.parser')
        
        link = soup.find('a', href=re.compile(r'/ru/news-room/fact-sheets/detail/'))
        if link:
            title = link.text.strip()
            url = "https://www.who.int" + link['href']
            return {"title": title, "url": url, "source": "ВОЗ (WHO)"}
    except Exception:
        pass
    return None